"""Run a simulation script with guard rails.

What this does and does not protect against:

* It runs in its own directory under ``data/simulations/<id>/`` with ``-I``
  (no environment variables, no user site-packages), a scrubbed environment
  (no API keys), a hard timeout, and a wrapper that disables sockets before the
  script's first line.
* It is **not** an operating-system sandbox. A determined script could still
  write files or exhaust memory. The import allowlist in ``coder.py`` and this
  wrapper stop accidents and casual misuse, not an adversary.
"""

import asyncio
import hashlib
import json
import logging
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)

# Prepended by the runner: blocks network access, then runs the simulation.
_SANDBOX = '''"""Generated by research_agent.experiments.runner - do not edit."""
import os
import runpy
import socket
import sys

# -I implies -P, so the script's own directory is not on sys.path: the generated
# `sim_params` module would be unreachable. Add exactly this directory (the
# experiment's own), nothing else.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


class _BlockedSocket(socket.socket):
    def __init__(self, *args, **kwargs):
        raise RuntimeError("network access is disabled inside the simulation sandbox")


def _blocked(*args, **kwargs):
    raise RuntimeError("network access is disabled inside the simulation sandbox")


socket.socket = _BlockedSocket
socket.create_connection = _blocked
socket.getaddrinfo = _blocked

runpy.run_path(sys.argv[1], run_name="__main__")
'''


REQUIRED_RESULT_KEYS = ("n", "metric", "test", "value", "p_value")


def contract_problems(result: Optional[dict], require_cells: bool = False) -> list:
    """What the result line is missing, as feedback for the script writer."""
    if not isinstance(result, dict) or not result:
        return ["no JSON result object was printed"]
    problems = [f"'{key}' is missing from the result" for key in REQUIRED_RESULT_KEYS
                if result.get(key) in (None, "")]
    values = result.get("values")
    p_values = result.get("p_values")
    if not isinstance(values, list) or not values:
        problems.append("'values' must be a non-empty list of replication estimates")
    elif not isinstance(p_values, list) or len(p_values) != len(values):
        problems.append("'p_values' must be a list as long as 'values'")
    if require_cells:
        cells = result.get("cells")
        if not isinstance(cells, list) or not cells:
            problems.append("'cells' must list the metric for every grid sample size")
        elif any(not isinstance(cell, dict) or "n" not in cell or "metric" not in cell
                 for cell in cells):
            problems.append("every entry in 'cells' needs 'n' and 'metric'")
    return problems


PARAM_NAMES = (
    "N", "EFFECT", "NOISE", "ALPHA", "SEED", "REPLICATIONS",
    # Meta designs add the grid, the inner-trial count and the threshold.
    "GRID", "TRIALS", "REFERENCE_N", "THRESHOLD", "COMPARISON", "METRIC_KIND",
)


def parse_result(stdout: str) -> Optional[dict]:
    """Last JSON object printed by the script, if it looks like a result."""
    for line in reversed((stdout or "").splitlines()):
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            data = json.loads(line)
        except (ValueError, TypeError):
            continue
        if isinstance(data, dict) and ("value" in data or "metric" in data):
            return data
    return None


class ScriptRunner:
    def __init__(
        self,
        base_dir: str = "data/simulations",
        timeout: float = 180.0,
        python: Optional[str] = None,
        max_output: int = 20_000,
    ):
        # Absolute: the script runs with cwd=its own directory, so a relative
        # base directory would be resolved twice and the sandbox path would not
        # exist ("data/simulations/<id>/data/simulations/<id>/_sandbox.py").
        self.base_dir = Path(base_dir).resolve()
        self.timeout = float(timeout or 180.0)
        self.python = python or sys.executable
        self.max_output = int(max_output)

    def experiment_dir(self, experiment_id: str) -> Path:
        return self.base_dir / experiment_id

    def _environment(self) -> dict:
        """Minimal environment: no API keys, no PYTHONPATH, temp dirs only."""
        keep = ("PATH", "SYSTEMROOT", "SYSTEMDRIVE", "TEMP", "TMP", "HOME", "USERPROFILE")
        env = {key: os.environ[key] for key in keep if key in os.environ}
        env.update({"PYTHONIOENCODING": "utf-8", "PYTHONDONTWRITEBYTECODE": "1"})
        return env

    def write_params(self, directory: Path, params: dict) -> Path:
        """Write the protocol numbers the script reads (``import sim_params``)."""
        lines = ["\"\"\"Generated by research_agent.experiments.runner - do not edit.\"\"\""]
        for name in PARAM_NAMES:
            if name in params:
                lines.append(f"{name} = {params[name]!r}")
        path = (directory / "sim_params.py").resolve()
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return path

    def run(
        self,
        experiment_id: str,
        code: str,
        params: Optional[dict] = None,
        timeout: Optional[float] = None,
    ) -> dict:
        """Write the script, execute it, return a structured outcome."""
        directory = self.experiment_dir(experiment_id)
        directory.mkdir(parents=True, exist_ok=True)
        script_path = (directory / "sim.py").resolve()
        wrapper_path = (directory / "_sandbox.py").resolve()
        script_path.write_text(code, encoding="utf-8")
        wrapper_path.write_text(_SANDBOX, encoding="utf-8")
        if params:
            self.write_params(directory, params)
        limit = float(timeout or self.timeout)

        started = time.time()
        timed_out = False
        stdout = stderr = ""
        exit_code = -1
        job_attached = False
        try:
            from .win_job import attach_job_limits
            # Kindprozess statt subprocess.run: So kann der OS-Limit-Job
            # (Vorschlag 2: fst concreto Speichergrenze + Kill-on-Close)
            # an das HANDLE investiert werden, bevor der Code laeuft.
            child = subprocess.Popen(
                [self.python, "-I", str(wrapper_path), str(script_path)],
                cwd=str(directory),
                env=self._environment(),
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            job_attached = attach_job_limits(child)
            try:
                out, errout = child.communicate(timeout=limit)
            except subprocess.TimeoutExpired:
                child.kill()
                out, errout = child.communicate()
                raise
            stdout = (out or "")[: self.max_output]
            stderr = (errout or "")[: self.max_output]
            exit_code = child.returncode
            if not job_attached:
                import logging
                logging.getLogger(__name__).debug(
                    "Job-Object-Begrenz nicht angewandt (nicht-Windows "
                    "oder API-Misserfolg): die Import-Allowlist bleibt "
                    "die einzige Schutzschicht fuer dieses Kind.")
        except subprocess.TimeoutExpired as exc:
            timed_out = True
            stdout = (exc.stdout or "")[: self.max_output] if isinstance(exc.stdout, str) else ""
            stderr = f"timeout after {limit:.0f}s"
            exit_code = -9
        except Exception as exc:  # noqa: BLE001 - report, never crash the cycle
            stderr = f"{type(exc).__name__}: {exc}"
            exit_code = -1

        duration = round(time.time() - started, 2)
        result = parse_result(stdout) if not timed_out else None
        ok = exit_code == 0 and result is not None
        error = ""
        if timed_out:
            error = f"timeout: script did not finish within {limit:.0f}s"
        elif exit_code != 0:
            error = (stderr.strip().splitlines()[-1] if stderr.strip() else f"exit code {exit_code}")[:300]
        elif result is None:
            error = "no JSON result line in the output"

        try:
            (directory / "result.json").write_text(
                json.dumps(result or {}, indent=2, ensure_ascii=False), encoding="utf-8"
            )
            (directory / "stdout.txt").write_text(stdout, encoding="utf-8")
            (directory / "stderr.txt").write_text(stderr, encoding="utf-8")
        except OSError:
            pass

        digest = hashlib.sha256(code.encode("utf-8")).hexdigest()
        return {
            "ok": ok,
            "error": error,
            "result": result or {},
            "stdout": stdout,
            "stderr": stderr,
            "exit_code": exit_code,
            "duration_s": duration,
            "timed_out": timed_out,
            "script_path": str(script_path),
            "script_sha256": digest,
        }

    async def run_async(
        self, experiment_id: str, code: str, params: Optional[dict] = None
    ) -> dict:
        """Run off the event loop so the research loop keeps answering."""
        return await asyncio.to_thread(self.run, experiment_id, code, params)

    @staticmethod
    def protocol_params(protocol, n: Optional[int] = None,
                        replications: Optional[int] = None,
                        smoke: bool = False) -> dict:
        reference = int(n if n is not None else getattr(protocol, "n", 30))
        params = {
            "N": reference,
            "EFFECT": float(getattr(protocol, "effect", 0.3)),
            "NOISE": float(getattr(protocol, "noise", 1.0)),
            "ALPHA": float(getattr(protocol, "alpha", 0.05)),
            "SEED": int(getattr(protocol, "seed", 1)),
            "REPLICATIONS": int(
                replications if replications is not None
                else getattr(protocol, "replications", 5)
            ),
        }
        if getattr(protocol, "is_meta", False):
            grid = list(protocol.normalized_grid())
            trials = int(getattr(protocol, "trials", 0) or 0)
            if smoke:
                # One cheap cell: the point is the contract, not the estimate.
                grid = [reference]
                trials = min(max(10, trials), 20)
            params.update({
                "GRID": grid,
                "TRIALS": trials,
                "REFERENCE_N": reference,
                "THRESHOLD": float(getattr(protocol, "threshold", 0.0) or 0.0),
                "COMPARISON": str(getattr(protocol, "comparison", "at_least")),
                "METRIC_KIND": str(getattr(protocol, "metric_kind", "")),
            })
        return params

    async def smoke_test(
        self, experiment_id: str, protocol, code: str,
        n: int = 30, timeout: float = 45.0,
    ) -> dict:
        """Run the script once at a tiny sample size before the real study.

        This is the cheapest place to catch a broken script: it proves the code
        executes, reads its numbers, and prints the agreed result line - before
        any result exists that could be mistaken for a finding. A timeout or a
        wrong shape is returned as feedback for the writer, not as data.
        """
        params = self.protocol_params(
            protocol, n=min(int(n), int(protocol.n)), replications=1, smoke=True
        )
        run = await self.run_async(f"{experiment_id}_smoke", code, params)
        problems = contract_problems(
            run.get("result"), require_cells=bool(getattr(protocol, "is_meta", False))
        )
        if run.get("ok") and problems:
            run["ok"] = False
            run["error"] = "; ".join(problems)
        run["problems"] = problems
        run["params"] = params
        return run
